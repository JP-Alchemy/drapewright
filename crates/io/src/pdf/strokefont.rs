/// An i or j whose dot went astray (lost with a line it sat on): its
/// strokes but the last, the dot.
pub(crate) fn without_dot(c: char) -> Option<&'static [Stroke]> {
    let strokes = glyph(c)?;
    matches!(c, 'i' | 'j').then(|| &strokes[..strokes.len() - 1])
}

