//! A stroke font of typewriter-style technical lettering, for reading
//! lettering that pattern CAD prints through plotter drivers as pen
//! strokes: monospaced, with small serifs, curves of short straight lines
//! and a slashed zero. Drawn for Drapewright on a grid where capitals are 10
//! units tall from the baseline (y up), lowercase letters 6.7, ascenders
//! 10.2 and descenders reach -2.4; letters sit about x = 0.

/// One pen stroke through its points.
pub(crate) type Stroke = &'static [(f64, f64)];

/// The characters the font has.
pub(crate) const CHARS: &str =
    "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789.,-+()[]!@:/\\_'\"?%=*&";

/// A small diamond (a full stop, the dot of an i) centred on (x, y).
macro_rules! dot {
    ($x:expr, $y:expr) => {
        &[
            ($x, $y + 0.45),
            ($x + 0.45, $y),
            ($x, $y - 0.45),
            ($x - 0.45, $y),
            ($x, $y + 0.45),
        ]
    };
}

/// A round shape of the given half-width from `y0` to `y1`: straight sides
/// with corners cut twice.
macro_rules! ring {
    ($w:expr, $y0:expr, $y1:expr) => {
        &[
            (-0.9, $y1),
            (0.9, $y1),
            ($w - 0.8, $y1 - 0.8),
            ($w, $y1 - 2.4),
            ($w, $y0 + 2.4),
            ($w - 0.8, $y0 + 0.8),
            (0.9, $y0),
            (-0.9, $y0),
            (-$w + 0.8, $y0 + 0.8),
            (-$w, $y0 + 2.4),
            (-$w, $y1 - 2.4),
            (-$w + 0.8, $y1 - 0.8),
            (-0.9, $y1),
        ]
    };
}

