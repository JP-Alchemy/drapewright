/// Width of `text` drawn `height` pixels tall.
pub fn text_width(text: &str, height: f32) -> f32 {
    let n = text.chars().count() as f32;
    if n == 0.0 {
        return 0.0;
    }
    let unit = height / HEIGHT;
    ((n - 1.0) * ADVANCE + 4.0) * unit
}

/// The strokes of `text`, `height` pixels tall, centred on `(cx, cy)`.
pub fn text_centred(text: &str, cx: f32, cy: f32, height: f32) -> Option<Path> {
    let unit = height / HEIGHT;
    let left = cx - text_width(text, height) / 2.0;
    let top = cy - height / 2.0;
    let mut path = PathBuilder::new();
    for (i, c) in text.chars().enumerate() {
        let x0 = left + i as f32 * ADVANCE * unit;
        for stroke in glyph(c) {
            let mut points = stroke.iter().map(|(x, y)| (x0 + x * unit, top + y * unit));
            if let Some((x, y)) = points.next() {
                path.move_to(x, y);
                for (x, y) in points {
                    path.line_to(x, y);
                }
            }
        }
    }
    path.finish()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_id_character_has_a_glyph() {
        for c in "0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ-.()_".chars() {
            assert!(!glyph(c).is_empty(), "{c}");
        }
        assert!(text_centred("e12", 50.0, 50.0, 12.0).is_some());
        assert!(text_centred(" ", 50.0, 50.0, 12.0).is_none());
        // Three characters: two advances and one glyph width.
        assert!((text_width("p12", 6.0) - 15.0).abs() < 1e-6);
    }
}
